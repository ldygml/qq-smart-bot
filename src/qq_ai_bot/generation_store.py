from __future__ import annotations

import sqlite3
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


@dataclass(frozen=True)
class GenerationRecord:
    id: int
    file_name: str
    display_name: str
    kind: str
    prompt: str
    summary: str
    source: str
    research: bool
    status: str
    error: str
    size: int
    created_at: str
    completed_at: str

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "file_name": self.file_name,
            "display_name": self.display_name,
            "kind": self.kind,
            "prompt": self.prompt,
            "summary": self.summary,
            "source": self.source,
            "research": self.research,
            "status": self.status,
            "error": self.error,
            "size": self.size,
            "created_at": self.created_at,
            "completed_at": self.completed_at,
        }


class GenerationStore:
    """Persistent index for artifacts generated by the website or QQ."""

    def __init__(self, database_path: Path | str) -> None:
        self.database_path = Path(database_path)
        self.database_path.parent.mkdir(parents=True, exist_ok=True)
        with self._connect() as connection:
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS generated_artifacts (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    file_name TEXT NOT NULL DEFAULT '',
                    display_name TEXT NOT NULL DEFAULT '',
                    kind TEXT NOT NULL DEFAULT 'file',
                    prompt TEXT NOT NULL DEFAULT '',
                    summary TEXT NOT NULL DEFAULT '',
                    source TEXT NOT NULL DEFAULT 'web',
                    research INTEGER NOT NULL DEFAULT 0,
                    status TEXT NOT NULL DEFAULT 'running',
                    error TEXT NOT NULL DEFAULT '',
                    size INTEGER NOT NULL DEFAULT 0,
                    created_at TEXT NOT NULL,
                    completed_at TEXT NOT NULL DEFAULT ''
                )
                """
            )
            connection.execute(
                """
                CREATE INDEX IF NOT EXISTS idx_generated_artifacts_created
                ON generated_artifacts(created_at DESC)
                """
            )

    def _connect(self) -> sqlite3.Connection:
        connection = sqlite3.connect(self.database_path, timeout=10)
        connection.row_factory = sqlite3.Row
        return connection

    @staticmethod
    def _now() -> str:
        return datetime.now(timezone.utc).isoformat(timespec="seconds")

    def start(
        self,
        *,
        kind: str,
        prompt: str,
        research: bool = False,
        source: str = "web",
    ) -> int:
        with self._connect() as connection:
            cursor = connection.execute(
                """
                INSERT INTO generated_artifacts (
                    file_name, display_name, kind, prompt, source,
                    research, status, created_at
                ) VALUES ('', '', ?, ?, ?, ?, 'running', ?)
                """,
                (
                    kind[:40],
                    prompt[:12_000],
                    source[:20],
                    int(research),
                    self._now(),
                ),
            )
            return int(cursor.lastrowid)

    def complete(
        self,
        record_id: int,
        *,
        file_name: str,
        display_name: str,
        kind: str,
        summary: str,
        size: int,
    ) -> None:
        with self._connect() as connection:
            connection.execute(
                """
                UPDATE generated_artifacts
                SET file_name = ?, display_name = ?, kind = ?, summary = ?,
                    status = 'ready', error = '', size = ?, completed_at = ?
                WHERE id = ?
                """,
                (
                    file_name,
                    display_name[:240],
                    kind[:40],
                    summary[:2000],
                    max(0, int(size)),
                    self._now(),
                    record_id,
                ),
            )

    def fail(self, record_id: int, error: str) -> None:
        with self._connect() as connection:
            connection.execute(
                """
                UPDATE generated_artifacts
                SET status = 'failed', error = ?, completed_at = ?
                WHERE id = ?
                """,
                (error[:2000], self._now(), record_id),
            )

    def record_artifact(
        self,
        *,
        file_name: str,
        display_name: str,
        kind: str,
        prompt: str,
        summary: str,
        source: str = "qq",
        research: bool = False,
        size: int = 0,
    ) -> int:
        now = self._now()
        with self._connect() as connection:
            cursor = connection.execute(
                """
                INSERT INTO generated_artifacts (
                    file_name, display_name, kind, prompt, summary, source,
                    research, status, size, created_at, completed_at
                ) VALUES (?, ?, ?, ?, ?, ?, ?, 'ready', ?, ?, ?)
                """,
                (
                    file_name,
                    display_name[:240],
                    kind[:40],
                    prompt[:12_000],
                    summary[:2000],
                    source[:20],
                    int(research),
                    max(0, int(size)),
                    now,
                    now,
                ),
            )
            return int(cursor.lastrowid)

    def list(self, *, limit: int = 40) -> list[GenerationRecord]:
        with self._connect() as connection:
            rows = connection.execute(
                """
                SELECT * FROM generated_artifacts
                ORDER BY id DESC LIMIT ?
                """,
                (max(1, min(200, int(limit))),),
            ).fetchall()
        return [self._record(row) for row in rows]

    def get(self, record_id: int) -> GenerationRecord | None:
        with self._connect() as connection:
            row = connection.execute(
                "SELECT * FROM generated_artifacts WHERE id = ?",
                (record_id,),
            ).fetchone()
        return self._record(row) if row is not None else None

    def for_file(self, file_name: str) -> GenerationRecord | None:
        with self._connect() as connection:
            row = connection.execute(
                """
                SELECT * FROM generated_artifacts
                WHERE file_name = ? AND status = 'ready'
                ORDER BY id DESC LIMIT 1
                """,
                (file_name,),
            ).fetchone()
        return self._record(row) if row is not None else None

    def delete(self, record_id: int) -> GenerationRecord | None:
        record = self.get(record_id)
        if record is None:
            return None
        with self._connect() as connection:
            connection.execute(
                "DELETE FROM generated_artifacts WHERE id = ?",
                (record_id,),
            )
        return record

    @staticmethod
    def _record(row: sqlite3.Row) -> GenerationRecord:
        return GenerationRecord(
            id=int(row["id"]),
            file_name=str(row["file_name"] or ""),
            display_name=str(row["display_name"] or ""),
            kind=str(row["kind"] or "file"),
            prompt=str(row["prompt"] or ""),
            summary=str(row["summary"] or ""),
            source=str(row["source"] or ""),
            research=bool(row["research"]),
            status=str(row["status"] or "failed"),
            error=str(row["error"] or ""),
            size=int(row["size"] or 0),
            created_at=str(row["created_at"] or ""),
            completed_at=str(row["completed_at"] or ""),
        )
